// Copies the browser engine's economy into the Function App so both run the exact same rules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../../web/src/engine/idle/economy.js');
const dest = path.resolve(here, '../src/shared/economy.js');
const banner = '// GENERATED by scripts/sync-engine.mjs from web/src/engine/idle/economy.js — do not edit.\n';
if (!fs.existsSync(src)) {
  // Deployed packages don't contain the web app; the committed copy is used as-is.
  console.log('engine source not found; keeping existing src/shared/economy.js');
  process.exit(0);
}
fs.writeFileSync(dest, banner + fs.readFileSync(src, 'utf8'));
console.log('synced economy.js');
