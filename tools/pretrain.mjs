// Trains the factory "Terra Autopilot" brains shipped with the app (curriculum over several routes).
// usage: node tools/pretrain.mjs  → writes web/src/engine/data/brains.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const E = path.join(root, 'web/src/engine');
const imp = (p) => import(path.join(E, p));

const { Graph } = await imp('graph.js');
const { World } = await imp('world.js');
const { CitySim } = await imp('sim/city-sim.js');
const { bootcamp } = await imp('sim/bootcamp.js');
const { MotorwaySim } = await imp('sim/motorway-sim.js');
const { GeoSim } = await imp('sim/geo-sim.js');
const { Coastline, buildLaneGraph } = await imp('geo/geo.js');
const { createRng } = await imp('math/rng.js');

const worlds = {};
for (const id of ['brisbane', 'goldcoast', 'sydney', 'melbourne']) {
  const data = (await imp(`data/maps/${id}.js`)).default;
  worlds[id] = new World(Graph.fromCompact(data)).generate();
}

// ---- city: bootcamp — every brain drives every route each generation ----
const tasks = [];
for (const [id, seeds] of [['brisbane', [2, 6, 11]], ['goldcoast', [5, 9]], ['sydney', [3, 7]], ['melbourne', [10, 4]]]) {
  for (const seed of seeds) {
    const r = worlds[id].suggestRoute(createRng(seed));
    if (r) tasks.push({ world: worlds[id], start: r.start, target: r.target });
  }
}
const camp = bootcamp(tasks, {
  generations: 70,
  populationSize: 70,
  onGeneration: (e) => e.generation % 10 === 0 && console.log(`bootcamp gen ${e.generation}: mean progress ${(e.best * 100).toFixed(0)}% best brain, ${e.arrivals} arrivals over ${e.routes} routes`),
});
let brain = camp.best;
// generalisation check: fleet across Brisbane
{
  const w = worlds.brisbane;
  let delivered = 0, crashed = 0;
  const sim = new CitySim(w, { brain, onEvent: (e) => (e.type === 'delivery' ? delivered++ : e.type === 'crash' ? crashed++ : 0) });
  sim.deployFleet(12);
  for (let i = 0; i < 6000; i++) sim.step();
  console.log(`city fleet check (Brisbane, 12 cars, 100 s): ${delivered} delivered, ${crashed} crashed`);
}

// ---- motorway ----
const mw = new MotorwaySim({ populationSize: 120 });
mw.start();
while (mw.trainer.generation < 25) mw.step();
console.log(`motorway best ${mw.trainer.bestFitness.toFixed(0)}`);

// ---- sea & air ----
const coast = new Coastline();
const geo = {};
for (const [domain, routes] of [['sea', [['PBNE', 'TANG'], ['PBNE', 'NOUP'], ['PBNE', 'POMP'], ['PBNE', 'AKLP'], ['PBNE', 'SUVA']]], ['air', [['BNE', 'AKL'], ['BNE', 'NAN'], ['BNE', 'HIR'], ['BNE', 'DPS']]]]) {
  let b = null;
  for (const [from, to] of routes) {
    const sim = new GeoSim(domain, { coast, graph: buildLaneGraph(domain), brain: b, populationSize: 70 });
    sim.setRoute(from, to);
    sim.startTraining();
    let arrived = 0;
    sim.onEvent = (e) => e.type === 'generation' && (arrived = e.arrived);
    while (sim.trainer.generation < 12) sim.step();
    b = sim.trainer.best;
    console.log(`${domain} ${from}→${to}: last gen arrived ${arrived}/70`);
  }
  geo[domain] = b;
}

const out = `// Generated by tools/pretrain.mjs — factory brains so a fleet can drive before you train your own.
export const FACTORY_BRAINS = ${JSON.stringify({ city: brain, motorway: mw.trainer.best, sea: geo.sea, air: geo.air, trainedAt: new Date().toISOString() })};
`;
fs.writeFileSync(path.join(E, 'data/brains.js'), out);
console.log('wrote data/brains.js', (out.length / 1024).toFixed(1), 'KB');
